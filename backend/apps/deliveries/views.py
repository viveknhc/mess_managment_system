class DeliveryFilter(django_filters.FilterSet):
    date_from = django_filters.DateFilter(field_name="delivery_date", lookup_expr="gte")
    date_to = django_filters.DateFilter(field_name="delivery_date", lookup_expr="lte")
    delivery_date = django_filters.DateFilter(field_name="delivery_date")
    status = django_filters.CharFilter(field_name="status")
    customer = django_filters.UUIDFilter(field_name="customer_id")
    subscription = django_filters.UUIDFilter(field_name="subscription_id")
    assigned_staff = django_filters.UUIDFilter(field_name="assigned_staff_id")
    route = django_filters.UUIDFilter(field_name="customer__route_id")
    no_route = django_filters.BooleanFilter(field_name="customer__route", lookup_expr="isnull")

    class Meta:
        model = Delivery
        fields = ["status", "customer", "subscription", "assigned_staff", "delivery_date"]


class DeliveryViewSet(TenantScopedViewSet):
    """Deliveries: list, today, status update, kitchen counts.

    - OWNER/MANAGER: full access.
    - DELIVERY_STAFF: today's deliveries assigned to them or unassigned; run statuses only.
    - KITCHEN_STAFF: view kitchen counts only.
    - No create/delete — generated by DeliveryService.
    """

    queryset = (
        Delivery.objects.select_related("customer__route", "meal", "assigned_staff")
        .prefetch_related("subscription__items")
        .all()
    )
    serializer_class = DeliveryListSerializer
    permission_classes = [IsAuthenticated, RoleBasedPermission]
    filterset_class = DeliveryFilter
    ordering_fields = [
        "delivery_date",
        "customer__name",
        "customer__address",
        "meal__name",
        "status",
        "assigned_staff__name",
        "delivered_at",
    ]
    http_method_names = ["get", "post", "patch", "head", "options"]

    role_map = {
        "list": [Role.OWNER, Role.MANAGER, Role.DELIVERY_STAFF],
        "retrieve": [Role.OWNER, Role.MANAGER, Role.DELIVERY_STAFF],
        "today": [Role.OWNER, Role.MANAGER, Role.DELIVERY_STAFF],
        "update_status": [Role.OWNER, Role.MANAGER, Role.DELIVERY_STAFF],
        "undo": [Role.OWNER, Role.MANAGER, Role.DELIVERY_STAFF],
        # Customers skip through the portal (/portal/subscriptions/{id}/skip/), which applies plan rules.
        "skip": [Role.OWNER, Role.MANAGER],
        "kitchen_counts": [Role.OWNER, Role.MANAGER, Role.KITCHEN_STAFF],
        "kitchen_meal": [Role.OWNER, Role.MANAGER, Role.KITCHEN_STAFF],
        "today_summary": [Role.OWNER, Role.MANAGER, Role.DELIVERY_STAFF, Role.KITCHEN_STAFF],
    }

    def get_queryset(self):
        qs = super().get_queryset()
        if self.request.user.role == Role.CUSTOMER:
            qs = qs.filter(customer__user=self.request.user)
        return self._staff_scope(qs)

    def _staff_scope(self, qs):
        """Delivery staff work today's run only: deliveries assigned to them, or not yet
        assigned (marking one claims it). Never another staff member's or another day's.

        If the mess turns delivery routes off, PENDING deliveries of customers still on a
        route (assigned by that route) are open to everyone again; marking claims them."""
        user = self.request.user
        if user.role != Role.DELIVERY_STAFF:
            return qs
        visible = Q(assigned_staff=user) | Q(assigned_staff__isnull=True)
        if not RouteService.is_enabled(user.business_id):
            visible |= Q(status=DeliveryStatus.PENDING, customer__route__isnull=False)
        return qs.filter(delivery_date=timezone.localdate()).filter(visible)

    @action(detail=False, methods=["get"])
    def today(self, request):
        """GET /deliveries/today/ — today's deliveries (filters: ?route=, ?no_route=, ?status=)."""
        qs = self._staff_scope(DeliverySelector.get_today(request.user.business_id))
        qs = self.filterset_class(request.query_params, queryset=qs, request=request).qs
        qs = StableOrderingFilter().filter_queryset(request, qs, self)
        page = self.paginate_queryset(qs)
        if page is not None:
            serializer = DeliveryListSerializer(page, many=True)
            return self.get_paginated_response(serializer.data)
        serializer = DeliveryListSerializer(qs, many=True)
        return Response(serializer.data)

    @action(detail=True, methods=["patch"], url_path="status")
    def update_status(self, request, pk=None):
        """PATCH /deliveries/{id}/status/ — update delivery status."""
        delivery = self.get_object()
        serializer = DeliveryStatusUpdateSerializer(data=request.data)
        serializer.is_valid(raise_exception=True)
        new_status = serializer.validated_data["status"]
        is_staff = request.user.role == Role.DELIVERY_STAFF
        # Delivery staff only run deliveries; skipping/cancelling is the owner's (or customer's) call.
        if is_staff and new_status not in RUN_STATUSES:
            return Response(
                {
                    "error": {
                        "code": "PERMISSION_DENIED",
                        "message": "Delivery staff can only mark deliveries out, delivered or not delivered.",
                        "fields": {},
                    }
                },
                status=status.HTTP_403_FORBIDDEN,
            )
        try:
            delivery = DeliveryService.update_status(
                delivery,
                new_status,
                notes=serializer.validated_data.get("notes", ""),
                staff=request.user if is_staff else None,
            )
        except ValueError as e:
            return Response(
                {"error": {"code": "INVALID_TRANSITION", "message": str(e), "fields": {}}},
                status=status.HTTP_400_BAD_REQUEST,
            )
        return Response(DeliveryListSerializer(delivery).data)

    @action(detail=True, methods=["post"])
    def undo(self, request, pk=None):
        """POST /deliveries/{id}/undo/ — back to PENDING shortly after a mis-tap."""
        delivery = self.get_object()
        try:
            delivery = DeliveryService.undo_status(delivery)
        except ValueError as e:
            return Response(
                {"error": {"code": "INVALID_TRANSITION", "message": str(e), "fields": {}}},
                status=status.HTTP_400_BAD_REQUEST,
            )
        return Response(DeliveryListSerializer(delivery).data)

    @action(detail=True, methods=["post"])
    def skip(self, request, pk=None):
        """POST /deliveries/{id}/skip/ — skip this delivery."""
        delivery = self.get_object()
        reason = request.data.get("reason", "")
        try:
            skip = DeliveryService.skip_meal(delivery, reason=reason)
        except ValueError as e:
            return Response(
                {"error": {"code": "VALIDATION_ERROR", "message": str(e), "fields": {}}},
                status=status.HTTP_400_BAD_REQUEST,
            )
        return Response({"id": str(skip.id), "skip_date": str(skip.skip_date), "reason": skip.reason})

    @action(detail=False, methods=["get"])
    def kitchen_counts(self, request):
        """GET /deliveries/kitchen_counts/ — today's meal totals."""
        counts = DeliverySelector.get_kitchen_counts(request.user.business_id)
        return Response(list(counts))

    @action(detail=False, methods=["get"])
    def kitchen_meal(self, request):
        """GET /deliveries/kitchen_meal/?meal=<id> — today's customers for one meal (kitchen drill-down)."""
        meal_id = request.query_params.get("meal", "")
        try:
            uuid.UUID(meal_id)
        except ValueError:
            return _error("VALIDATION_ERROR", "Pass ?meal=<meal id>.")
        data = DeliverySelector.get_kitchen_meal(request.user.business_id, meal_id)
        if data is None:
            return _error("NOT_FOUND", "Meal not found.", status.HTTP_404_NOT_FOUND)
        return Response(data)

    @action(detail=False, methods=["get"])
    def today_summary(self, request):
        """GET /deliveries/today_summary/ — today's counts by status (no customer data)."""
        return Response(DeliverySelector.get_today_summary(request.user.business_id))


def _error(code, message, http_status=status.HTTP_400_BAD_REQUEST):
    return Response({"error": {"code": code, "message": message, "fields": {}}}, status=http_status)


class DeliveryRouteViewSet(TenantScopedViewSet):
    """Delivery routes (feature ``delivery_routes``) — OWNER/MANAGER manage, every write
    goes through RouteService so upcoming deliveries follow the route's staff member."""

    queryset = DeliveryRoute.objects.select_related("staff").all()
    serializer_class = DeliveryRouteSerializer
    permission_classes = [IsAuthenticated, RoleBasedPermission, requires_feature(DELIVERY_ROUTES)]
    ordering_fields = ["name", "customer_count"]
    pagination_class = None  # a mess has a handful of routes
    http_method_names = ["get", "post", "patch", "delete", "head", "options"]

    role_map = {
        "list": [Role.OWNER, Role.MANAGER],
        "retrieve": [Role.OWNER, Role.MANAGER],
        "create": [Role.OWNER, Role.MANAGER],
        "partial_update": [Role.OWNER, Role.MANAGER],
        "destroy": [Role.OWNER, Role.MANAGER],
    }

    def get_queryset(self):
        return (
            super()
            .get_queryset()
            .annotate(customer_count=Count("customers"))
            .prefetch_related("customers")
            .order_by("name")
        )

    def _save(self, request, route=None):
        serializer = self.get_serializer(route, data=request.data, partial=route is not None)
        serializer.is_valid(raise_exception=True)
        data = serializer.validated_data
        try:
            route = RouteService.save_route(
                business_id=request.user.business_id,
                route=route,
                name=data.get("name", route.name if route else ""),
                staff=data["staff"] if "staff" in data else (route.staff if route else None),
                notes=data.get("notes", route.notes if route else ""),
                customer_ids=data.get("customer_ids"),
            )
        except ValueError as e:
            return None, _error("VALIDATION_ERROR", str(e))
        return self.get_queryset().get(pk=route.pk), None

    def create(self, request, *args, **kwargs):
        route, err = self._save(request)
        if err:
            return err
        return Response(self.get_serializer(route).data, status=status.HTTP_201_CREATED)

    def partial_update(self, request, *args, **kwargs):
        route, err = self._save(request, self.get_object())
        if err:
            return err
        return Response(self.get_serializer(route).data)

    def destroy(self, request, *args, **kwargs):
        RouteService.delete_route(self.get_object())
        return Response(status=status.HTTP_204_NO_CONTENT)
